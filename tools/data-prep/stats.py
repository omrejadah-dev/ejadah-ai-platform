import sys, pandas as pd, numpy as np
pd.set_option("display.width", 250); pd.set_option("display.max_rows", 200); pd.set_option("display.max_columns", 30)
df = pd.read_csv(sys.argv[1], dtype=str, keep_default_na=False, low_memory=False)
df.columns = ["file","deal_id","category","type","price","area","ppm","date","region","city","district","plan","plot","notes","source","type_ai"]
df["year"] = df["file"].str.slice(0,4)
for c in ["price","area","ppm"]: df[c] = pd.to_numeric(df[c], errors="coerce")
df["dt"] = pd.to_datetime(df["date"], dayfirst=True, errors="coerce")
print("TOTAL ROWS", len(df)); print()
print("ROWS PER YEAR FILE"); print(df.groupby("year").size().to_string()); print()
print("DUPLICATE deal_id:", df["deal_id"].duplicated().sum(), " unique:", df["deal_id"].nunique()); print()
print("EMPTY % PER COLUMN"); print((df.replace("", np.nan).isna().mean()*100).round(1).to_string()); print()
print("DATE parse failures:", df["dt"].isna().sum(), " min:", df["dt"].min(), " max:", df["dt"].max())
print("file-year vs date-year mismatch:", (df["dt"].dt.year.astype("Int64").astype(str) != df["year"]).sum()); print()
print("CATEGORY"); print(df["category"].value_counts().to_string()); print()
print("TYPE"); print(df["type"].value_counts().to_string()); print()
print("TYPE_AI (ذكاء عقارساس) non-empty:", (df["type_ai"]!="").sum()); print(df["type_ai"].value_counts().head(20).to_string()); print()
print("SOURCE"); print(df["source"].value_counts().to_string()); print()
print("REGION"); print(df["region"].value_counts().to_string()); print()
print("CITY (top 40)"); print(df["city"].value_counts().head(40).to_string()); print("unique cities:", df["city"].nunique()); print()
print("DISTRICT unique:", df["district"].nunique()); print(df["district"].value_counts().head(40).to_string()); print()
print("NOTES non-empty:", (df["notes"]!="").sum()); print(df["notes"].value_counts().head(15).to_string()); print()
print("PRICE describe"); print(df["price"].describe(percentiles=[.01,.05,.25,.5,.75,.95,.99]).round(0).to_string()); print()
print("AREA describe"); print(df["area"].describe(percentiles=[.01,.05,.25,.5,.75,.95,.99]).round(1).to_string()); print()
print("PPM describe"); print(df["ppm"].describe(percentiles=[.01,.05,.25,.5,.75,.95,.99]).round(0).to_string()); print()
print("price<=1000:", (df["price"]<=1000).sum(), " area<=1:", (df["area"]<=1).sum(), " ppm<=10:", (df["ppm"]<=10).sum(), " ppm>=100000:", (df["ppm"]>=100000).sum())
print("ppm consistency |price/area - ppm| > 5%:", ((df["price"]/df["area"] - df["ppm"]).abs() > 0.05*df["ppm"]).sum()); print()
print("PLAN empty:", (df["plan"]=="").sum(), " PLOT empty:", (df["plot"]=="").sum(), " unique plans:", df["plan"].nunique())
print("plan sample:", df["plan"].drop_duplicates().sample(15, random_state=1).tolist())
print("plot sample:", df["plot"].drop_duplicates().sample(15, random_state=1).tolist()); print()
print("MEDIAN PPM per YEAR x TYPE (Jeddah residential, top types)")
j = df[(df["city"].str.contains("جد")) & (df["category"]=="سكني")]
top = j["type"].value_counts().head(4).index
print(j[j["type"].isin(top)].pivot_table(index="year", columns="type", values="ppm", aggfunc="median").round(0).to_string()); print()
print("DEALS per YEAR x TYPE (Jeddah residential)")
print(j[j["type"].isin(top)].pivot_table(index="year", columns="type", values="deal_id", aggfunc="count").to_string()); print()
print("TOP 25 districts by deals (Jeddah), with 2025-2026 median ppm land")
l = j[(j["type"]=="قطعة أرض") & (j["year"].isin(["2025","2026"]))]
print(l.groupby("district")["ppm"].agg(["count","median"]).sort_values("count", ascending=False).head(25).round(0).to_string())
